# STEP 6: Check whether a user is logged in
def login_required(view_function):
    from functools import wraps

    @wraps(view_function)
    def wrapped_view(*args, **kwargs):
        if "user_id" not in session:
            flash("Please log in to access this page.", "error")
            return redirect(url_for("login"))

        return view_function(*args, **kwargs)

    return wrapped_view


# STEP 1: Connect to SQLite or PostgreSQL database

def get_db_connection():
    database_url = os.environ.get("DATABASE_URL")

    if database_url:
        connection = psycopg.connect(
            database_url,
            row_factory=dict_row
        )
        return connection

    connection = sqlite3.connect(DATABASE)
    connection.row_factory = sqlite3.Row
    return connection

# Execute SQL queries with the correct database placeholders

def execute_query(connection, query, parameters=()):
    if os.environ.get("DATABASE_URL"):
        query = query.replace("?", "%s")

    return connection.execute(query, parameters)


# STEP 2: Create database tables

def init_db():
    connection = get_db_connection()

    try:
        if os.environ.get("DATABASE_URL"):
            # PostgreSQL tables
            connection.execute("""
                CREATE TABLE IF NOT EXISTS users (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    full_name TEXT NOT NULL,
                    email TEXT NOT NULL UNIQUE,
                    password_hash TEXT NOT NULL,
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    selected_career TEXT
                )
            """)
            connection.execute("""
                ALTER TABLE users
                ADD COLUMN IF NOT EXISTS selected_career TEXT
            """)

            connection.execute("""
                CREATE TABLE IF NOT EXISTS assessments (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id BIGINT NOT NULL REFERENCES users(id),
                    career TEXT NOT NULL,
                    total_questions INTEGER NOT NULL,
                    correct_answers INTEGER NOT NULL,
                    percentage DOUBLE PRECISION NOT NULL,
                    skill_level TEXT NOT NULL,
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                )
            """)

            connection.execute("""
                CREATE TABLE IF NOT EXISTS assessment_skills (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    assessment_id BIGINT NOT NULL
                        REFERENCES assessments(id) ON DELETE CASCADE,
                    skill_name TEXT NOT NULL,
                    total_questions INTEGER NOT NULL,
                    correct_answers INTEGER NOT NULL,
                    percentage DOUBLE PRECISION NOT NULL
                )
            """)

            connection.execute("""
                CREATE TABLE IF NOT EXISTS learning_plan_progress (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id BIGINT NOT NULL
                        REFERENCES users(id) ON DELETE CASCADE,
                    assessment_id BIGINT NOT NULL
                        REFERENCES assessments(id) ON DELETE CASCADE,
                    day_number INTEGER NOT NULL
                        CHECK (day_number BETWEEN 1 AND 7),
                    completed BOOLEAN NOT NULL DEFAULT FALSE,
                    completed_at TIMESTAMP,
                    UNIQUE (user_id, assessment_id, day_number)
                )
            """)

        else:
            # SQLite tables
            connection.execute("""
                CREATE TABLE IF NOT EXISTS users (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    full_name TEXT NOT NULL,
                    email TEXT NOT NULL COLLATE NOCASE UNIQUE,
                    password_hash TEXT NOT NULL,
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    selected_career TEXT
                )
            """)

            columns = {
                row["name"]
                for row in connection.execute(
                    "PRAGMA table_info(users)"
                ).fetchall()
            }

            if "selected_career" not in columns:
                connection.execute(
                    "ALTER TABLE users ADD COLUMN selected_career TEXT"
                )

            connection.execute("""
                CREATE TABLE IF NOT EXISTS assessments (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    user_id INTEGER NOT NULL,
                    career TEXT NOT NULL,
                    total_questions INTEGER NOT NULL,
                    correct_answers INTEGER NOT NULL,
                    percentage REAL NOT NULL,
                    skill_level TEXT NOT NULL,
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    FOREIGN KEY (user_id) REFERENCES users(id)
                )
            """)

            connection.execute("""
                CREATE TABLE IF NOT EXISTS assessment_skills (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    assessment_id INTEGER NOT NULL,
                    skill_name TEXT NOT NULL,
                    total_questions INTEGER NOT NULL,
                    correct_answers INTEGER NOT NULL,
                    percentage REAL NOT NULL,
                    FOREIGN KEY (assessment_id)
                        REFERENCES assessments(id)
                        ON DELETE CASCADE
                )
            """)

            connection.execute("""
                CREATE TABLE IF NOT EXISTS learning_plan_progress (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    user_id INTEGER NOT NULL,
                    assessment_id INTEGER NOT NULL,
                    day_number INTEGER NOT NULL
                        CHECK (day_number BETWEEN 1 AND 7),
                    completed INTEGER NOT NULL DEFAULT 0,
                    completed_at TIMESTAMP,
                    UNIQUE (user_id, assessment_id, day_number),
                    FOREIGN KEY (user_id)
                        REFERENCES users(id) ON DELETE CASCADE,
                    FOREIGN KEY (assessment_id)
                        REFERENCES assessments(id) ON DELETE CASCADE
                )
            """)

        connection.commit()

    except Exception:
        connection.rollback()
        raise

    finally:
        connection.close()

# Initialize database tables when the application loads.
init_db()


