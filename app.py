@app.route("/login", methods=["GET", "POST"])
def login():

    if request.method == "POST":

        email = request.form.get("email", "").strip().lower()
        password = request.form.get("password", "")

        if not email or not password:
            flash("Please enter your email and password.", "error")
            return redirect(url_for("login"))

        connection = get_db_connection()

        user = execute_query(
            connection,
            "SELECT * FROM users WHERE email = ?",
            (email,)
        ).fetchone()

        connection.close()

        if user and check_password_hash(
                user["password_hash"], password
        ):
                session.clear()

                session["user_id"] = user["id"]
                session["user_name"] = user["full_name"]
                session["user_email"] = user["email"]

                flash("Login successful! Welcome to SkillBridge.", "success")
                return redirect(url_for("dashboard"))

        flash("Invalid email or password.", "error")
        return redirect(url_for("login"))

    return render_template("login.html")


@app.route("/dashboard")
@login_required
def dashboard():
    connection = get_db_connection()

    try:
        # Get logged-in user's information
        user = execute_query(
            connection,
            """
            SELECT full_name, email, selected_career
            FROM users
            WHERE id = ?
            """,
            (session["user_id"],)
        ).fetchone()

        # Get assessment analytics
        analytics = execute_query(
            connection,
            """
            SELECT
            COUNT(*) AS total_assessments,
            COALESCE(
                  ROUND(CAST(AVG(percentage) AS NUMERIC), 1),
                  0
            ) AS average_score,
            COALESCE(MAX(percentage), 0)
                    AS best_score
            FROM assessments
            WHERE user_id = ?
            """,
            (session["user_id"],)
        ).fetchone()

        # Get the five most recent assessments
        recent_assessments = execute_query(
            connection,
            """
            SELECT
                id,
                career,
                total_questions,
                correct_answers,
                percentage,
                skill_level,
                created_at
            FROM assessments
            WHERE user_id = ?
            ORDER BY created_at DESC, id DESC
            LIMIT 5
            """,
            (session["user_id"],)
        ).fetchall()

        # Get assessment scores for the progress chart
        progress_data = execute_query(
            connection,
            """
            SELECT
                created_at,
                percentage
            FROM assessments
            WHERE user_id = ?
            ORDER BY created_at ASC, id ASC
            """,
            (session["user_id"],)
        ).fetchall()

    finally:
        connection.close()

    return render_template(
        "dashboard.html",
        user=user,
        analytics=analytics,
        recent_assessments=recent_assessments,
        progress_data=progress_data
    )

